export type CodigosPostalesPorMunicipio = Readonly<Record<string, readonly string[]>>;

export function normalizarClavePostal(valor?: string): string {
  return (valor ?? '')
    .toUpperCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^A-Z0-9]+/g, ' ')
    .trim();
}

export function clavePostal(provincia?: string, municipio?: string): string {
  return `${normalizarClavePostal(provincia)}|${normalizarClavePostal(municipio)}`;
}

